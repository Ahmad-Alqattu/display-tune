class Tr:
    def __init__(self, lang):
        self.lang = lang if lang in STRINGS else 'en'

    def __call__(self, key, **kw):
        strings = STRINGS[self.lang]
        text = strings[key] if key in strings else STRINGS['en'][key]
        return text.format(**kw) if kw else text

    @property
    def rtl(self):
        return self.lang in RTL_LANGUAGES
